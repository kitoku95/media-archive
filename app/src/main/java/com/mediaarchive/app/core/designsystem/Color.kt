/**
 * Returns the primary swatch preview color for a given palette.
 */
fun AppThemePalette.swatchColor(isDark: Boolean = false): Color = when (this) {
    AppThemePalette.NEUTRAL_TAUPE -> if (isDark) Color(0xFFC8BEB2) else Color(0xFF5C5346)
    AppThemePalette.DEEP_CRIMSON -> if (isDark) Color(0xFFFFB3B4) else Color(0xFF8B1E24)
    AppThemePalette.DEEP_FOREST -> if (isDark) Color(0xFF8BD6B9) else Color(0xFF1B4D3E)
    AppThemePalette.DEEP_SAPPHIRE -> if (isDark) Color(0xFFA6C8FF) else Color(0xFF1A365D)
}
